"""Generate deterministic warehouse-task CSV data for graph-import experiments.

The column layout mirrors the useful shape of the LaDe/Jilin delivery CSV: one task
per row, an execution region and agent, timestamps, and start/target coordinates.
It intentionally uses warehouse terms instead of delivery or geographic semantics.
"""

from __future__ import annotations

import argparse
import csv
import random
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Iterator


HEADER = (
    "task_id",
    "zone_id",
    "warehouse",
    "robot_id",
    "rack_id",
    "slot_id",
    "cargo_id",
    "task_type",
    "priority",
    "release_time",
    "assigned_time",
    "pickup_time",
    "completed_time",
    "start_x",
    "start_y",
    "target_x",
    "target_y",
    "level",
    "bay",
    "depth_row",
    "ds",
)

RACK_X = (8.0, 13.0, 18.0, 23.0, 28.0)
RACK_Y = (4.3, 9.4, 14.5)


def zone_for_rack(rack_id: int) -> str:
    return "ABC"[(rack_id - 1) % len(RACK_Y)]


def rack_position(rack_id: int) -> tuple[float, float]:
    if not 1 <= rack_id <= len(RACK_X) * len(RACK_Y):
        raise ValueError("rack_id is outside the warehouse layout")
    index = rack_id - 1
    return RACK_X[index // len(RACK_Y)], RACK_Y[index % len(RACK_Y)]


def format_time(value: datetime) -> str:
    return value.strftime("%Y-%m-%d %H:%M:%S")


def make_row(task_number: int, rng: random.Random, base_day: date, robot_count: int) -> dict[str, str | int | float]:
    robot_id = rng.randrange(1, robot_count + 1)
    rack_id = rng.randrange(1, len(RACK_X) * len(RACK_Y) + 1)
    level = rng.randrange(1, 4)
    bay = rng.randrange(1, 7)
    depth_row = rng.randrange(1, 3)
    target_x, target_y = rack_position(rack_id)
    release = datetime.combine(base_day, datetime.min.time()) + timedelta(
        hours=8, seconds=rng.randrange(8 * 60 * 60)
    )
    assigned = release + timedelta(seconds=rng.randrange(5, 91))
    picked = assigned + timedelta(seconds=rng.randrange(20, 181))
    completed = picked + timedelta(seconds=rng.randrange(60, 481))
    priority = rng.choices(("normal", "high", "urgent"), weights=(82, 15, 3), k=1)[0]
    pickup_column = (robot_id - 1) % 20
    pickup_row = (robot_id - 1) // 20
    return {
        "task_id": f"WT-{task_number:09d}",
        "zone_id": zone_for_rack(rack_id),
        "warehouse": "WH-01",
        "robot_id": f"HR-{robot_id:03d}",
        "rack_id": rack_id,
        "slot_id": f"R{rack_id:02d}-L{level}-C{bay}-D{depth_row}",
        "cargo_id": f"BX-{task_number:09d}",
        "task_type": "putaway",
        "priority": priority,
        "release_time": format_time(release),
        "assigned_time": format_time(assigned),
        "pickup_time": format_time(picked),
        "completed_time": format_time(completed),
        "start_x": round(1.55 + pickup_column * 1.48, 2),
        "start_y": round(18.9 + pickup_row * 0.46, 2),
        "target_x": target_x,
        "target_y": target_y,
        "level": level,
        "bay": bay,
        "depth_row": depth_row,
        "ds": base_day.strftime("%Y%m%d"),
    }


def iter_rows(count: int, seed: int, day: date, robot_count: int) -> Iterator[dict[str, str | int | float]]:
    if count < 1:
        raise ValueError("count must be positive")
    if robot_count < 1:
        raise ValueError("robot_count must be positive")
    rng = random.Random(seed)
    for task_number in range(1, count + 1):
        yield make_row(task_number, rng, day, robot_count)


def estimate_graph_scale(task_count: int) -> dict[str, int]:
    """Estimate the minimum graph generated by Task + release/completion Events."""
    return {
        "tasks": task_count,
        "events": task_count * 2,
        "minimum_nodes": task_count * 3 + 1,
        "minimum_relationships": task_count * 10,
    }


def write_dataset(path: Path, count: int, seed: int, day: date, robot_count: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=HEADER)
        writer.writeheader()
        writer.writerows(iter_rows(count, seed, day, robot_count))


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate warehouse task CSV data for graph experiments.")
    parser.add_argument("--output", type=Path, default=Path("data/generated/warehouse_tasks.csv"))
    parser.add_argument("--count", type=int, default=10_000, help="number of task rows to generate")
    parser.add_argument("--robot-count", type=int, default=100)
    parser.add_argument("--seed", type=int, default=20261026)
    parser.add_argument("--day", type=date.fromisoformat, default=date(2026, 10, 26))
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="estimate scale without writing CSV")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    if args.count < 1 or args.robot_count < 1:
        raise SystemExit("--count and --robot-count must be positive")
    estimate = estimate_graph_scale(args.count)
    if args.dry_run:
        print(f"任务行数: {args.count}")
        print(f"预计 Task 节点: {estimate['tasks']}")
        print(f"预计 Event 节点: {estimate['events']}")
        print(f"预计最少节点数: {estimate['minimum_nodes']}")
        print(f"预计最少关系数: {estimate['minimum_relationships']}")
        return
    if args.output.exists() and not args.overwrite:
        raise SystemExit(f"output already exists: {args.output}; add --overwrite to replace it")
    write_dataset(args.output, args.count, args.seed, args.day, args.robot_count)
    print(f"已生成: {args.output}")
    print(f"任务行数: {args.count}; 预计最少图节点: {estimate['minimum_nodes']}")


if __name__ == "__main__":
    main()
